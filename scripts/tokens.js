// Builds packages/ui/src/tokens.css from the DTCG 2025.10 token files in packages/ui/tokens/
// (ADR-0020): light.tokens.json fills `:root`, dark.tokens.json fills `.dark`.
//   node scripts/tokens.js            write tokens.css
//   node scripts/tokens.js --check    fail when tokens.css is not what the token files give
//   node scripts/tokens.js --figma <light.json> <dark.json>
//                                     fail when a Figma variable export differs from the token files
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const tokensDir = path.join(root, 'packages/ui/tokens');
const cssFile = path.join(root, 'packages/ui/src/tokens.css');
const MODES = [
  { file: 'light.tokens.json', selector: ':root' },
  { file: 'dark.tokens.json', selector: '.dark' },
];

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

// Flattens nested groups to `name` → token; the CSS name is the path joined with `-`.
function flatten(group, prefix = []) {
  return Object.entries(group).flatMap(([key, node]) => {
    if (key.startsWith('$')) return [];
    const name = [...prefix, key];
    return '$value' in node ? [[name.join('-'), node]] : flatten(node, name);
  });
}

function toCss(token, name) {
  const value = token.$value;
  if (token.$type === 'color') {
    if (value.colorSpace !== 'oklch') throw new Error(`${name}: only oklch colours are supported`);
    const alpha = value.alpha === undefined || value.alpha === 1 ? '' : ` / ${value.alpha}`;
    return `oklch(${value.components.join(' ')}${alpha})`;
  }
  if (token.$type === 'dimension') return `${value.value}${value.unit}`;
  throw new Error(`${name}: unsupported $type ${token.$type}`);
}

function buildCss() {
  const blocks = MODES.map(({ file, selector }) => {
    const lines = flatten(readJson(path.join(tokensDir, file))).map(
      ([name, token]) => `  --${name}: ${toCss(token, name)};`
    );
    return `${selector} {\n${lines.join('\n')}\n}\n`;
  });
  return `/* Generated by scripts/tokens.js from packages/ui/tokens/*.tokens.json. Do not edit. */\n\n${blocks.join('\n')}`;
}

// oklch → gamma-encoded sRGB in 0..1, clamped (CSS Color 4).
function oklchToSrgb([l, c, h]) {
  const hr = (h * Math.PI) / 180;
  const a = c * Math.cos(hr);
  const b = c * Math.sin(hr);
  const l1 = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m1 = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s1 = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const linear = [
    4.0767416621 * l1 - 3.3077115913 * m1 + 0.2309699292 * s1,
    -1.2684380046 * l1 + 2.6097574011 * m1 - 0.3413193965 * s1,
    -0.0041960863 * l1 - 0.7034186147 * m1 + 1.707614701 * s1,
  ];
  return linear.map((x) => {
    const v = x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
    return Math.min(1, Math.max(0, v));
  });
}

function toRgb255(value) {
  if (typeof value === 'string') {
    const hex = value.replace('#', '');
    const channels = hex.match(/../g).map((pair) => Number.parseInt(pair, 16));
    return channels.length === 4 ? channels : [...channels, 255];
  }
  const rgb = value.colorSpace === 'oklch' ? oklchToSrgb(value.components) : value.components;
  return [...rgb.map((x) => Math.round(x * 255)), Math.round((value.alpha ?? 1) * 255)];
}

// Figma exports sRGB; a token matches when each channel is within 1 of 255.
function compareFigma(lightExport, darkExport) {
  const problems = [];
  MODES.forEach(({ file }, index) => {
    const ours = new Map(flatten(readJson(path.join(tokensDir, file))));
    const theirs = new Map(
      // A Figma group such as `color/background` arrives as `color-background`.
      flatten(readJson([lightExport, darkExport][index])).map(([name, token]) => [
        name.replace(/^colou?rs?-/, ''),
        token,
      ])
    );
    for (const [name, token] of ours) {
      if (token.$type !== 'color') continue;
      const figma = theirs.get(name);
      if (!figma) {
        problems.push(`${file}: ${name} is missing in the Figma export`);
        continue;
      }
      const a = toRgb255(token.$value);
      const b = toRgb255(figma.$value);
      if (a.some((channel, i) => Math.abs(channel - b[i]) > 1)) {
        problems.push(`${file}: ${name} is rgba(${a}) in the tokens, rgba(${b}) in Figma`);
      }
    }
  });
  return problems;
}

const [flag, ...rest] = process.argv.slice(2);
if (flag === '--figma') {
  if (rest.length !== 2) {
    console.error('Usage: node scripts/tokens.js --figma <light export> <dark export>');
    process.exit(2);
  }
  const problems = compareFigma(...rest.map((file) => path.resolve(file)));
  if (problems.length > 0) {
    console.error(`Figma and the token files differ:\n${problems.join('\n')}`);
    process.exit(1);
  }
  console.log('Figma matches the token files.');
} else if (flag === '--check') {
  if (!fs.existsSync(cssFile) || fs.readFileSync(cssFile, 'utf8') !== buildCss()) {
    console.error('packages/ui/src/tokens.css is out of date. Run: pnpm tokens');
    process.exit(1);
  }
} else {
  fs.writeFileSync(cssFile, buildCss());
}
